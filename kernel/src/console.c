static struct limine_framebuffer *g_fb = NULL;
static size_t cursor_x = 0;
static size_t cursor_y = 0;
static uint32_t text_color = 0xFFFFFF;
static uint32_t bg_color = 0x0A0A1A;

static const size_t CHAR_W = 8;
static const size_t CHAR_H = 8;
static const size_t SCALE = 2;   // 2x scale for better visibility

static void draw_char(size_t col, size_t row, char c) {
    if (!g_fb) return;
    if (c < 32 || c > 127) c = '?';

    const uint8_t *glyph = font8x8[c - 32];
    size_t px = col * CHAR_W * SCALE;
    size_t py = row * CHAR_H * SCALE;

    for (size_t gy = 0; gy < 8; gy++) {
        for (size_t gx = 0; gx < 8; gx++) {
            uint32_t color = (glyph[gy] & (1 << gx)) ? text_color : bg_color;
            for (size_t sy = 0; sy < SCALE; sy++) {
                for (size_t sx = 0; sx < SCALE; sx++) {
                    size_t x = px + gx * SCALE + sx;
                    size_t y = py + gy * SCALE + sy;
                    if (x < g_fb->width && y < g_fb->height) {
                        volatile uint32_t *ptr = g_fb->address;
                        ptr[y * (g_fb->pitch / 4) + x] = color;
                    }
                }
            }
        }
    }
}

void console_init(struct limine_framebuffer *fb) {
    g_fb = fb;
    cursor_x = 0;
    cursor_y = 0;
    text_color = 0xFFFFFF;
    bg_color = 0x0A0A1A;
}

void console_clear(uint32_t color) {
    if (!g_fb) return;
    bg_color = color;
    volatile uint32_t *ptr = g_fb->address;
    size_t pixels = g_fb->height * (g_fb->pitch / 4);
    for (size_t i = 0; i < pixels; i++) {
        ptr[i] = color;
    }
    cursor_x = 0;
    cursor_y = 0;
}

void console_set_color(uint32_t fg) {
    text_color = fg;
}

void console_set_cursor(size_t col, size_t row) {
    cursor_x = col;
    cursor_y = row;
}

void console_newline(void) {
    cursor_x = 0;
    cursor_y++;
    // Simple scroll not implemented yet - just wrap
    size_t max_rows = g_fb ? (g_fb->height / (CHAR_H * SCALE)) : 30;
    if (cursor_y >= max_rows) {
        cursor_y = 0;
    }
}

void console_print(const char *str) {
    if (!str) return;
    while (*str) {
        if (*str == '\n') {
            console_newline();
        } else {
            draw_char(cursor_x, cursor_y, *str);
            cursor_x++;
            size_t max_cols = g_fb ? (g_fb->width / (CHAR_W * SCALE)) : 80;
            if (cursor_x >= max_cols) {
                console_newline();
            }
        }
        str++;
    }
}

void console_print_at(size_t col, size_t row, const char *str) {
    size_t old_x = cursor_x;
    size_t old_y = cursor_y;
    cursor_x = col;
    cursor_y = row;
    console_print(str);
    cursor_x = old_x;
    cursor_y = old_y;
}

void console_print_hex(uint64_t value) {
    char buf[17];
    const char *hex = "0123456789ABCDEF";
    for (int i = 15; i >= 0; i--) {
        buf[i] = hex[value & 0xF];
        value >>= 4;
    }
    buf[16] = 0;
    // Skip leading zeros
    char *p = buf;
    while (*p == '0' && *(p+1)) p++;
    console_print("0x");
    console_print(p);
}

void console_print_dec(uint64_t value) {
    if (value == 0) {
        console_print("0");
        return;
    }
    char buf[21];
    int i = 20;
    buf[i] = 0;
    while (value > 0) {
        buf[--i] = '0' + (value % 10);
        value /= 10;
    }
    console_print(&buf[i]);
}
